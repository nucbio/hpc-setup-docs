#!/usr/bin/env python3
"""Write packages.qmd from hpc-setup/pkgs.json and _variables.yml from hpc-setup/VERSION.

Source: $HPC_SETUP_DIR (default: ../hpc-setup).
"""
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SETUP = Path(os.environ.get("HPC_SETUP_DIR", ROOT.parent / "hpc-setup"))
SRC = SETUP / "pkgs.json"
OUT = ROOT / "packages.qmd"
VARS = ROOT / "_variables.yml"

CATEGORIES = [
    ("bioinformatics", "Bioinformatic tools"),
    ("nanopore", "Nanopore tools"),
    ("development", "Languages"),
    ("terminal", "Terminal tools"),
    ("core", "Core tools"),
    ("core-library", "Core libraries"),
    ("meta", "Meta-modules"),
]


def cell(text):
    return str(text).replace("|", "\\|").strip()


def main():
    version = (SETUP / "VERSION").read_text().strip()
    VARS.write_text(f'version: "{version}"\n')
    pkgs = json.loads(SRC.read_text())
    lines = [
        "---",
        'title: "Packages"',
        "---",
        "",
        "<!-- Generated by scripts/packages.py from pkgs.json. Do not edit. -->",
        "",
        f"Packages in hpc-setup **v{version}**. Versions may change in newer releases.",
        "",
        "Load a package with `module load NAME`.",
        "",
    ]
    known = {key for key, _ in CATEGORIES}
    extra = sorted({p.get("module_category", "") for p in pkgs.values()} - known)
    for key, title in CATEGORIES + [(c, c or "Other") for c in extra]:
        rows = sorted(
            ((n, p) for n, p in pkgs.items()
             if p.get("module_category", "") == key and p.get("enabled", True)),
            key=lambda x: x[0].lower(),
        )
        if not rows:
            continue
        lines += [f"## {title}", "", "| Package | Version | Description |",
                  "|---|---|---|"]
        for name, p in rows:
            url = p.get("module_url")
            link = f"[{name}]({url})" if url else name
            lines.append(f"| {link} | {cell(p.get('pkg_version', ''))} "
                         f"| {cell(p.get('module_description', ''))} |")
        lines.append("")
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
